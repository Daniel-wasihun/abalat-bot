const locale = ref(localStorage.getItem('app_locale') || 'en');

export function setLocale(code) {
  locale.value = code;
  localStorage.setItem('app_locale', code);
}

export function useI18n() {
  const t = (key, vars = {}) => {
    const dict = messages[locale.value] || messages.en;
    let str = dict[key] ?? messages.en[key] ?? key;
    Object.entries(vars).forEach(([k, v]) => {
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
    });
    return str;
  };

  const currentLocale = computed(() => locale.value);
  const currentLocaleInfo = computed(() =>
    LOCALES.find(l => l.code === locale.value) || LOCALES[0]
  );

  return { t, locale: currentLocale, currentLocaleInfo, setLocale };
}

